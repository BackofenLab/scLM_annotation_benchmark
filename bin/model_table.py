#!/usr/bin/env python
"""Generate Table 1 (the annotation methods) from the sourced model facts.

``cache/result/model_facts.csv`` holds one row per (model, field) with the value, its source and
how it was checked. This script only formats it: it writes the table between the GENERATED markers
in ``sections/methods.tex``, so the typeset table cannot drift from its sources (style Rule 6).
Group and subcategory must agree with the figures' classification, or the script stops.

Usage:
    python bin/model_table.py [--facts cache/result/model_facts.csv]
                              [--target scLLMs_benchmark_paper/sections/methods.tex]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from manuscript_figures import _display  # noqa: E402
from plot_model_comparison import CATEGORY_TIERS, categorize_model, model_tier  # noqa: E402

BEGIN = "% BEGIN GENERATED by bin/model_table.py -- do not edit by hand"
END = "% END GENERATED by bin/model_table.py"
GROUPS = [("classical", "Baselines"), ("scLLM", "Single-cell language models"),
          ("LLM", "General-purpose LLMs")]
# Component abbreviations, defined in the caption. The text adapter of mmContext projects the text
# embedding into the joint space, the same job the projection heads do in the other two models.
PARTS = {"text_encoder": "TE", "text_decoder": "TD", "expression_encoder": "EE",
         "expression_decoder": "ED", "projection_heads": "heads", "text_adapter": "heads"}
ACCESS = {"open weights (licence-gated)": "open weights", "open-source software": "open source"}
# Wrapped columns are ragged right: justified text in narrow cells leaves wide gaps.
RAGGED = "\\raggedright\\arraybackslash"
COLUMNS = f"@{{}}l>{{{RAGGED}}}p{{3.1cm}}>{{{RAGGED}}}p{{1.75cm}}>{{{RAGGED}}}p{{3.85cm}}ll@{{}}"
CAPTION = (
    "Annotation methods compared in this benchmark. Subcategories follow the key of "
    "Figure~\\ref{fig:overview}B. "
    "Parameters count the learned weights of the checkpoint used here, with tied weights counted "
    "once: TE, text encoder; TD, text decoder (C2S-Scale is decoder-only; InstructCell's encoder "
    "and decoder share their word embeddings, counted with the TE); EE, expression encoder (for "
    "mmContext an adapter on the log-normalized expression of 10,000 preselected genes; for "
    "CellWhisperer a frozen Geneformer); "
    "ED, expression decoder, which InstructCell uses only to generate expression profiles; heads, "
    "projection and matching heads. CellTypist uses one logistic-regression model per dataset. "
    "For mixture-of-experts LLMs, "
    "the developer's total and, in brackets, the parameters active per token. Available: when the "
    "weights, software or API became public. Publication: the peer-reviewed paper or, if none, the "
    "preprint. Every entry, with its source, is in \\texttt{cache/result/model\\_facts.csv} in the "
    "repository.")


def si(n):
    """Three significant digits with a K/M/B/T suffix: 2614341888 -> 2.61B."""
    for div, suffix in ((1e12, "T"), (1e9, "B"), (1e6, "M"), (1e3, "K")):
        if n >= div:
            return f"{n / div:.3g}{suffix}"
    return str(n)


def parameters(v):
    if "parameters_total" not in v:
        counts = [int(x) for k, x in v.items() if k.startswith("parameters.model:")]
        return f"{si(min(counts))}--{si(max(counts))} per dataset"
    total = v["parameters_total"]
    if total == "none":
        return "--"
    if total == "not disclosed":
        return total
    text = si(int(total))
    if "parameters_active" in v:
        return f"{text} ({si(int(v['parameters_active']))} active)"
    parts = {}
    for key, abbr in PARTS.items():
        if f"parameters.{key}" in v:
            parts[abbr] = parts.get(abbr, 0) + int(v[f"parameters.{key}"])
    if list(parts.values()) == [int(total)]:
        return f"{text} ({next(iter(parts))})"
    return f"{text} ({', '.join(f'{abbr} {si(n)}' for abbr, n in parts.items())})" if parts else text


def publication(v):
    if v.get("publication_venue", "none") != "none":
        return f"{v['publication_venue']} {v['publication_date'][:7]}"
    if "preprint_date" in v:
        return f"preprint {v['preprint_date'][:7]}"
    return "--"


def rows(facts):
    tier_order = {k: i for tiers in CATEGORY_TIERS.values() for i, (k, *_rest) in enumerate(tiers)}
    labels = {k: label for tiers in CATEGORY_TIERS.values() for k, label, *_rest in tiers}
    out = []
    for model, g in facts.groupby("model"):
        v = dict(zip(g.field, g.value))
        if (v["group"], v["subcategory"]) != (categorize_model(model), model_tier(model)):
            raise SystemExit(f"{model}: facts say {v['group']}/{v['subcategory']}, the figures say "
                             f"{categorize_model(model)}/{model_tier(model)}")
        out.append({"group": v["group"], "tier": tier_order[v["subcategory"]],
                    "available": v["available_since"], "name": _display(model),
                    "cells": [_display(model), labels[v["subcategory"]],
                              ACCESS.get(v["access"], v["access"]), parameters(v),
                              v["available_since"][:7], publication(v)]})
    return out


def write_table(facts):
    entries = rows(facts)
    lines = [BEGIN, "\\begin{table*}[t]", "\\centering", "\\footnotesize",
             "\\setlength{\\tabcolsep}{4pt}",
             f"\\caption{{{CAPTION}}}", "\\label{tab:models}",
             f"\\begin{{tabular}}{{{COLUMNS}}}", "\\toprule",
             "\\textbf{Model} & \\textbf{Subcategory} & \\textbf{Access} & \\textbf{Parameters} & "
             "\\textbf{Available} & \\textbf{Publication} \\\\"]
    for key, title in GROUPS:
        lines += ["\\midrule", f"\\multicolumn{{6}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\"]
        for e in sorted((e for e in entries if e["group"] == key),
                        key=lambda e: (e["tier"], e["available"], e["name"])):
            lines.append(" & ".join(e["cells"]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", END]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--facts", default="cache/result/model_facts.csv")
    p.add_argument("--target", default="scLLMs_benchmark_paper/sections/methods.tex")
    args = p.parse_args()
    facts = pd.read_csv(args.facts, dtype=str)
    target = Path(args.target)
    text = target.read_text()
    block = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(block.findall(text)) != 1:
        raise SystemExit(f"{target}: expected exactly one block between the GENERATED markers")
    target.write_text(block.sub(lambda _m: write_table(facts), text))
    print(f"Wrote Table 1 ({facts.model.nunique()} models) into {target}")


if __name__ == "__main__":
    main()
