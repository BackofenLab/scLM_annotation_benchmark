#!/usr/bin/env python
"""Generate the supplementary table of the datasets from the sourced dataset facts.

``cache/result/dataset_facts.csv`` holds one row per (dataset, field) with the value, its source
and how it was checked. This script only formats it into a generated file that the supplement
inputs, so the typeset table cannot drift from its sources (style Rule 6). The datasets are the
columns, in the order of the result tables. A supplement cannot \\cite (the bioRxiv build gives each
part its own bibliography), so sources are named in author-year text taken from the bibliography,
and the Methods cite them.

Usage:
    python bin/dataset_table.py [--facts cache/result/dataset_facts.csv]
        [--out scLLMs_benchmark_paper/bioRxiv_template/supplementary_datasets_table_generated.tex]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from manuscript_figures import DATASET_ORDER  # noqa: E402

HEADER = "% GENERATED by bin/dataset_table.py -- do not edit by hand."
BIB = Path(__file__).resolve().parents[1] / "scLLMs_benchmark_paper" / "reference.bib"
RAGGED = "\\raggedright\\arraybackslash"
COLUMNS = f"@{{}}>{{{RAGGED}}}p{{3.9cm}}" + f">{{{RAGGED}}}p{{2.95cm}}" * 4 + "@{}"


def _count(value):
    return f"{int(value):,}"


def _tex(text):
    """Primes for the 10x chemistry ("3'") and the authors' apostrophe, as LaTeX writes them."""
    return str(text).replace("3'", "3$'$")


def _pair(a, b):
    return f"{_count(a)} and {_count(b)}"


def references(path=BIB):
    """Author-year text, "Gong et al. (2025)", of every entry with a one-line author field."""
    out = {}
    for key, body in re.findall(r"@\w+\{([^,\s]+),\n(.*?)\n\}", path.read_text(), re.S):
        author = re.search(r"^\s*author\s*=\s*\{(.*)\},\s*$", body, re.M)
        year = re.search(r"^\s*year\s*=\s*\{?(\d{4})", body, re.M)
        if author and year:
            names = [n.split(",")[0].strip() for n in author.group(1).split(" and ")]
            who = (names[0] if len(names) == 1 else " and ".join(names) if len(names) == 2
                   else f"{names[0]} et al.")
            out[key] = f"{who} ({year.group(1)})"
    return out


REFS = references()


# Rows of the table: (label, how to format a dataset's facts).
ROWS = [
    ("Source", lambda f: REFS[f["citation"]]),
    ("Organism", lambda f: f["organism"]),
    ("Tissue", lambda f: f["tissue"]),
    ("Donors", lambda f: (f"{f['donors']} ({f['stage']})" if "donors" in f else "--")),
    ("Technology", lambda f: _tex(f["technology"])),
    ("Cells as downloaded", lambda f: _count(f["cells_downloaded"])),
    ("Cells after quality control", lambda f: _count(f["cells_after_qc"])),
    ("Genes as downloaded", lambda f: _count(f["genes_downloaded"])),
    ("Genes after quality control", lambda f: _count(f["genes_after_qc"])),
    ("Cell types labeled", lambda f: _count(f["cell_types_labelled"])),
    ("Cell types scored", lambda f: _count(f["cell_types_scored"])),
    ("Labels", lambda f: f["labels"]),
    ("License", lambda f: f["license"]),
    ("Test sets (cells)", lambda f: _pair(f["test_cells_1000"], f["test_cells_10000"])),
]


def facts_by_dataset(facts):
    return {ds: dict(zip(g["field"], g["value"])) for ds, g in facts.groupby("dataset")}


# How a dataset is named inside a sentence; the column header keeps the capital.
IN_TEXT = {"human_pancreas": "human pancreas"}
NUMBER_WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine"}


def _name(by, ds):
    return IN_TEXT.get(ds, by[ds]["name"])


def caption(by):
    merged = [f"{_name(by, ds)} {by[ds]['cell_types_labelled']} to {by[ds]['cell_types_after_mapping']}"
              for ds in DATASET_ORDER
              if by[ds]["cell_types_after_mapping"] != by[ds]["cell_types_labelled"]]
    studies = {ds: by[ds]["studies"].split("; ") for ds in DATASET_ORDER}
    compiled = [ds for ds in DATASET_ORDER if len(studies[ds]) > 1]
    sentences = []
    for ds in compiled:
        keys = studies[ds]
        named = [REFS[k] for k in keys]
        cite = (" and ".join(named) if len(named) == 2
                else f"{NUMBER_WORDS.get(len(keys), len(keys))} studies, "
                     f"{', '.join(named[:-1])} and {named[-1]}")
        sentences.append(f"{_name(by, ds)} compiles {cite}")
    return (
        "\\textbf{Datasets of the benchmark.} Cells and genes of the files as downloaded and after "
        "quality control. Cell types labeled are the distinct labels of a file; scored are those "
        "left after the labels were mapped to the Cell Ontology, which merged some of the authors' "
        f"labels ({', '.join(merged)}), and that have at least 20 cells. A test set draws each "
        "scored cell type in proportion to its share of the dataset, with at least 20 cells, so "
        "rounding leaves some test sets a few cells short of 1,000 or 10,000. "
        f"{'; '.join(sentences)[0].upper()}{'; '.join(sentences)[1:]}. "
        "In the human pancreas data, quality "
        f"control removed {_tex(by['human_pancreas']['qc_removed'])}. HFRA, Human Fetal Retina "
        "Atlas; HIHA, Human Immune Health Atlas.")


def write_table(facts):
    by = facts_by_dataset(facts)
    missing = [ds for ds in DATASET_ORDER if ds not in by]
    if missing:
        raise SystemExit(f"no facts for {missing}")
    lines = [HEADER, "", "\\begin{table}[!ht]", "\\centering", "\\footnotesize",
             "\\setlength{\\tabcolsep}{4pt}", f"\\begin{{tabular}}{{{COLUMNS}}}", "\\toprule",
             " & " + " & ".join(f"\\textbf{{{by[ds]['name']}}}" for ds in DATASET_ORDER) + " \\\\",
             "\\midrule"]
    for label, cell in ROWS:
        lines.append(f"{label} & " + " & ".join(cell(by[ds]) for ds in DATASET_ORDER) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\captionsetup{position=below}",
              f"\\caption{{{caption(by)}}}", "\\label{supptab:datasets}", "\\end{table}", ""]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--facts", default="cache/result/dataset_facts.csv")
    p.add_argument("--out", default="scLLMs_benchmark_paper/bioRxiv_template/"
                                    "supplementary_datasets_table_generated.tex")
    args = p.parse_args()
    facts = pd.read_csv(args.facts, dtype=str)
    Path(args.out).write_text(write_table(facts))
    print(f"Wrote the datasets table ({facts.dataset.nunique()} datasets) to {args.out}")


if __name__ == "__main__":
    main()
