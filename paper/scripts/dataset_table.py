#!/usr/bin/env python
"""Generate the supplementary tables of the datasets and of the baselines' inputs.

``paper/data/dataset_facts.csv`` holds one row per dataset and field with the value, its source
and how it was checked; this script only formats it. The datasets are the columns, in the order of
the result tables. A supplementary table cannot cite, since each part of the supplement has its
own bibliography, so sources are named in author-year text taken from the bibliography.

    python paper/scripts/dataset_table.py [--facts CSV] [--out TEX]

The baselines table is written next to --out.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import pandas as pd

import paths
from methods import DATASET_ORDER, dataset_label

HEADER = "% GENERATED by bin/dataset_table.py -- do not edit by hand."
RAGGED = "\\raggedright\\arraybackslash"
COLUMNS = f"@{{}}>{{{RAGGED}}}p{{3.9cm}}" + f">{{{RAGGED}}}p{{2.95cm}}" * 4 + "@{}"


def _count(value):
    return f"{int(value):,}"


def _tex(text):
    """Primes for the 10x chemistry ("3'") and the authors' apostrophe, as LaTeX writes them."""
    return str(text).replace("3'", "3$'$")


def _pair(a, b):
    return f"{_count(a)} and {_count(b)}"


def references(path=paths.REFERENCES):
    """Author-year text, "Gong et~al. (2025)", of every entry with a one-line author field.

    The tie keeps "et al." on one line, as natbib does.
    """
    out = {}
    for key, body in re.findall(r"@\w+\{([^,\s]+),\n(.*?)\n\}", path.read_text(), re.S):
        author = re.search(r"^\s*author\s*=\s*\{(.*)\},\s*$", body, re.M)
        year = re.search(r"^\s*year\s*=\s*\{?(\d{4})", body, re.M)
        if author and year:
            names = [n.split(",")[0].strip() for n in author.group(1).split(" and ")]
            who = (names[0] if len(names) == 1 else " and ".join(names) if len(names) == 2
                   else f"{names[0]} et~al.")
            out[key] = f"{who} ({year.group(1)})"
    return out


REFS = references()


# Rows of the table: (label, how to format a dataset's facts).
ROWS = [
    ("Source", lambda f: REFS[f["citation"]]),
    ("Organism", lambda f: f["organism"]),
    ("Tissue", lambda f: f["tissue"]),
    ("Donors", lambda f: (f"{f['donors']} ({f['stage']})" if "donors" in f else "--")),
    ("Technology", lambda f: _tex(f["technology"])),
    ("Cells as downloaded", lambda f: _count(f["cells_downloaded"])),
    ("Cells after quality control", lambda f: _count(f["cells_after_qc"])),
    ("Genes as downloaded", lambda f: _count(f["genes_downloaded"])),
    ("Genes after quality control", lambda f: _count(f["genes_after_qc"])),
    ("Cell types", lambda f: _count(f["cell_types_labelled"])),
    ("Cell types scored", lambda f: _count(f["cell_types_scored"])),
    ("Labels", lambda f: f["labels"]),
    ("License", lambda f: f["license"]),
    ("Test sets (cells)", lambda f: _pair(f["test_cells_1000"], f["test_cells_10000"])),
]


def facts_by_dataset(facts):
    return {ds: dict(zip(g["field"], g["value"])) for ds, g in facts.groupby("dataset")}


NUMBER_WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight",
                9: "nine"}


def caption(by):
    merged = [f"{dataset_label(ds)} {by[ds]['cell_types_labelled']} to "
              f"{by[ds]['cell_types_after_mapping']}"
              for ds in DATASET_ORDER
              if by[ds]["cell_types_after_mapping"] != by[ds]["cell_types_labelled"]]
    studies = {ds: by[ds]["studies"].split("; ") for ds in DATASET_ORDER}
    compiled = [ds for ds in DATASET_ORDER if len(studies[ds]) > 1]
    sentences = []
    for ds in compiled:
        keys = studies[ds]
        named = [REFS[k] for k in keys]
        cite = (" and ".join(named) if len(named) == 2
                else f"{NUMBER_WORDS.get(len(keys), len(keys))} studies, "
                     f"{', '.join(named[:-1])} and {named[-1]}")
        sentences.append(f"{dataset_label(ds)} compiles {cite}")
    sources = ", and ".join(sentences)
    return (
        "\\textbf{Datasets of the benchmark.} Cells and genes of the files as downloaded and after "
        "quality control. Cell types gives the number of distinct labels of a file. Cell types "
        "scored counts those left after the labels were mapped to the Cell Ontology, which merged "
        f"some of the labels ({', '.join(merged)}), and that have at least 20 cells. A "
        "test set draws each scored cell type in proportion to its share of the dataset, with at "
        f"least 20 cells. {sources[0].upper()}{sources[1:]}. HFRA is the Human Fetal Retina Atlas "
        "and HIHA the Human Immune Health Atlas.")


def _breakable(name):
    """A model file name whose underscores may break the line, so a narrow column can hold it."""
    return str(name).replace("_", "\\_\\allowbreak{}")


# Rows of the baselines table: what each baseline was given for each dataset.
BASELINE_ROWS = [
    ("CellTypist model", lambda f: _breakable(f["celltypist_model"])),
    ("SingleR reference",
     lambda f: f"{f['singler_reference']}, {REFS[f['singler_reference_citation']]}"),
    ("scType tissue", lambda f: f["sctype_tissue"]),
    ("SCSA tissue", lambda f: f["scsa_tissue"]),
]
BASELINE_CAPTION = (
    "\\textbf{Inputs of the baselines.} CellTypist model names the pretrained model CellTypist "
    "used. SingleR reference gives the annotated data SingleR compared each cell with, a CELLxGENE "
    "dataset or the MonacoImmuneData reference of the celldex package. scType tissue and SCSA "
    "tissue name the tissue whose marker genes scType and SCSA scored. HFRA is the Human Fetal "
    "Retina Atlas and HIHA the Human Immune Health Atlas.")


def _dataset_table(by, rows, caption_text, label):
    """A table with one column per dataset, in the order of the result tables."""
    missing = [ds for ds in DATASET_ORDER if ds not in by]
    if missing:
        raise SystemExit(f"no facts for {missing}")
    lines = [HEADER, "", "\\begin{table}[!ht]", "\\centering", "\\footnotesize",
             "\\setlength{\\tabcolsep}{4pt}", f"\\begin{{tabular}}{{{COLUMNS}}}", "\\toprule",
             " & " + " & ".join(f"\\textbf{{{by[ds]['name']}}}" for ds in DATASET_ORDER) + " \\\\",
             "\\midrule"]
    for row_label, cell in rows:
        lines.append(f"{row_label} & " + " & ".join(cell(by[ds]) for ds in DATASET_ORDER) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\captionsetup{position=below}",
              f"\\caption{{{caption_text}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    return "\n".join(lines)


def write_table(facts):
    by = facts_by_dataset(facts)
    return _dataset_table(by, ROWS, caption(by), "supptab:datasets")


def write_baselines_table(facts):
    return _dataset_table(facts_by_dataset(facts), BASELINE_ROWS, BASELINE_CAPTION,
                          "supptab:baselines")


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--facts", default=str(paths.DATASET_FACTS))
    p.add_argument("--out",
                   default=str(paths.TABLES / "supplementary_datasets_table_generated.tex"))
    args = p.parse_args()
    facts = pd.read_csv(args.facts, dtype=str)
    Path(args.out).write_text(write_table(facts))
    baselines = Path(args.out).with_name("supplementary_baselines_table_generated.tex")
    baselines.write_text(write_baselines_table(facts))
    print(f"Wrote the datasets table ({facts.dataset.nunique()} datasets) to {args.out}"
          f" and the baselines table to {baselines}")


if __name__ == "__main__":
    main()
